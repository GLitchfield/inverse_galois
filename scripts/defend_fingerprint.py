"""defend_fingerprint -- block-incidence subset-orbit selector for gen12 disc-defense harden.

test 0052's `defend_harden.harden_pair` REUSES the held `w` verbatim over a smaller split prime and
got 0/80 improved: `idealprimedec`'s prime ordering is non-canonical across split primes, so a fixed
`w`-index selects a different `G`-orbit submodule -> a different `24Tt` (13/80 built a smaller disc but
the wrong group). This replaces the reuse-`w` step with a CANONICAL block-incidence fingerprint
selector (auto_log 2026-07-07 "gen12 kernel-submodule ALIGNMENT" + "Block-system / subfield alignment"
dives).

Theory (grounds the selector). `general_c2` builds `K = F(sqrt(prod_{j in S} p_j))` where `p_1..p_12`
are the primes of the deg-12 base `F` above a totally-split prime `q`, ordered by `idealprimedec`, and
`S` is the subset selected by `w`. The resulting `24Tt` is the closure group, an extension of
`G = Gal(F~/Q)` by the F_2[G]-submodule generated by the square-class of `prod_{j in S} p_j`. Since
`g in G` just permutes the primes, that submodule -- hence the `24Tt` -- depends only on the
`G`-ORBIT of the SUBSET `S`. The block systems of `G` are the subfields of `F` (`nfsubfields`), each a
`G`-invariant partition of the 12 primes; the multiset `{|S cap block|}` over all blocks of all
subfields is therefore a `G`-INVARIANT of the subset orbit. It is a canonical (order-independent) but
INCOMPLETE orbit invariant -- so it is used only as a PRE-FILTER: candidates whose block-incidence
fingerprint matches the held `S` are orbit-plausible, then certified by the validated self-relative
Frobenius density gate (same-group L1 ~ 0.05, diff-group ~ 1.06; `defend_harden.frob_density`/`l1`) and
finally by SAIR/Magma downstream -> no false positives possible.

Pipeline per behind pair (base, old_q, w_held):
  1. partitions(base, old_q) -> FP_held from S_held = {positions where w_held=1}.
  2. for each smaller totally-split prime q' < old_q on the SAME base:
       partitions(base, q'); enumerate w' (same popcount k) whose fingerprint == FP_held;
       build via defend_producer.sweep_base; keep r == target r, scoreable_disc strictly < ours and
       non-blank, density-L1 <= l1_max vs the held model.
  Survivors enqueue as `defend:<t>.<r>:harden:q<q'>`, priority 150 (the existing harden tag).

Usage:
  python scripts/defend_fingerprint.py --only 12232.0            # validate one pair (no enqueue)
  python scripts/defend_fingerprint.py --limit 40 --enqueue      # build + enqueue survivors
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import defend_harden  # noqa: E402  (reuse POOL/build_pool + frob_density/l1 density gate)
from igp import gp  # noqa: E402
from igp import searchstore as store  # noqa: E402

CKPT = ROOT / "data" / "processed" / "defend_fingerprint_winners.jsonl"
PARISIZE = 1_200_000_000


def block_partitions(base_asc, q: int, *, timeout: float = 180.0):
    """Block-system partitions of the 12 primes above `q` in the deg-12 base `F`.

    Returns [(subfield_degree, [block_id_1..block_id_12])] indexed so that position i (0-based)
    corresponds to `idealprimedec(nf,q)[i+1]` -- the SAME ordering `sweep_base` selects `w` against.
    Block ids identify which prime of the subfield each base-prime lies over; computed by reducing the
    subfield generator mod each prime and grouping equal residues. For primes dividing the field index
    the power-basis numerator degenerates, so we fall back to `nfmodpr` on the maximal-order element.
    Returns None on a non-split prime / gp failure.
    """
    cs = ",".join(str(int(c)) for c in list(base_asc)[::-1])
    body = (
        f"default(parisize,{PARISIZE});\n"
        f"f=Pol([{cs}],'y);nf=nfinit(f);sf=nfsubfields(nf);\n"
        f"q={int(q)};pr=idealprimedec(nf,q);\n"
        "if(#pr!=12,print(\"NP:\",#pr),"
        "mp=vector(#pr,j,nfmodprinit(nf,pr[j]));"
        "a=vector(#pr,j,nfmodpr(nf,Mod('y,f),mp[j]));"
        "bad=(nf.index%q==0);"
        "for(i=1,#sf,my(dg=poldegree(sf[i][1]),h,d,P,vals,reps,bid);"
        "if(dg>1&&dg<12,h=sf[i][2];d=denominator(h);P=h*d;"
        "if(!bad&&gcd(d,q)==1,vals=vector(#pr,j,subst(P,'y,a[j])),"
        "vals=vector(#pr,j,nfmodpr(nf,Mod(h,f),mp[j])));"
        "reps=List();bid=vector(#pr,x,0);"
        "for(j=1,#pr,my(fd=0);for(m=1,#reps,if(vals[j]===reps[m],bid[j]=m;fd=1;break));"
        "if(!fd,listput(reps,vals[j]);bid[j]=#reps));"
        "print(\"SUB\",dg,\":\",bid))))"
    )
    try:
        out = gp.script(body, timeout=timeout)
    except Exception:
        return None
    parts = []
    for ln in out.splitlines():
        ln = ln.strip()
        if ln.startswith("NP:"):
            return None
        if ln.startswith("SUB"):
            try:
                head, rest = ln.split(":", 1)
                dg = int(head[3:].strip())
                bids = [int(x) for x in rest.strip().strip("[]").split(",")]
                if len(bids) == 12:
                    parts.append((dg, bids))
            except Exception:
                continue
    return parts or None


def fingerprint(parts, S):
    """Canonical block-incidence fingerprint of subset `S` (a set of 0-based positions).

    For each subfield: the sorted multiset of |S cap block| over its blocks. The whole fingerprint is
    the sorted collection of (degree, that multiset) over subfields -- order-independent, so it is a
    genuine G-invariant even when two subfields share a degree.
    """
    per = []
    for dg, bids in parts:
        blocks = defaultdict(list)
        for i, b in enumerate(bids):
            blocks[b].append(i)
        counts = tuple(sorted(len(set(idxs) & S) for idxs in blocks.values()))
        per.append((dg, counts))
    return tuple(sorted(per))


def build_subsets_at(base_asc, subsets, q: int, *, timeout: float = 240.0):
    """Build general_c2(base, S, q) for every subset S in `subsets` in ONE bnfinit (amortized).

    Mirrors `defend_producer.sweep_base`'s radical construction but transposes it: one totally-split
    prime `q`, many kernel subsets. Returns {subset_index: (r, coeffs_ascending)} for the subsets whose
    prime-product is principal and give a valid degree-24 field.
    """
    if not subsets:
        return {}
    cs = ",".join(str(int(c)) for c in list(base_asc)[::-1])
    idxsets = [[j + 1 for j in combo] for combo in subsets]  # 1-based idealprimedec positions
    loop = (
        "for(s=1,#IDX, idx=IDX[s]; Jd=pr[idx[1]]; for(k=2,#idx, Jd=idealmul(bnf,Jd,pr[idx[k]])); "
        "pd=bnfisprincipal(bnf,Jd); if(!(#pd[1]>0 && vecmax(abs(pd[1]))>0), "
        "al=lift(nfbasistoalg(bnf,pd[2])); rr=rnfequation(f,'x^2-al); "
        "if(poldegree(rr)==24, g=polredbest(rr); print(s,\"|\",polsturm(g),\"|\",Vec(g)))))"
    )
    body = (
        f"default(parisize,{PARISIZE});\n"
        f"f=Pol([{cs}],'y);bnf=bnfinit(f);\n"
        f"q={int(q)};pr=idealprimedec(bnf,q);\n"
        f"if(#pr==12, IDX={idxsets};\n{loop});"
    )
    try:
        out = gp.script(body, timeout=timeout)
    except Exception:
        return {}
    res = {}
    for ln in out.splitlines():
        if "|" not in ln:
            continue
        try:
            ss, rs, vec = ln.split("|")
            coeffs = [int(x) for x in vec.strip("[] ").split(",")][::-1]
            if len(coeffs) == 25:
                res[int(ss) - 1] = (int(rs), coeffs)
        except Exception:
            continue
    return res


def matching_subsets(parts, fp_held, k, *, cap=4000):
    """All size-k subsets of {0..11} whose fingerprint matches `fp_held` (capped for safety)."""
    out = []
    for combo in itertools.combinations(range(12), k):
        S = set(combo)
        if fingerprint(parts, S) == fp_held:
            out.append(combo)
            if len(out) >= cap:
                break
    return out


def harden_pair(rec, *, l1_max: float = 0.15, per_pair: int = 2, hi: int = 60000,
                n_primes: int = 12):
    t, r = str(rec["t"]), str(rec["r"])
    target_r = int(r)
    base = rec["base"]
    w = rec["w"]
    old_q = int(rec["old_q"]) if rec["old_q"] else 10 ** 9
    our_disc = int(rec["ourDisc"])
    held_coeffs = [int(x) for x in rec["line"].split(",")]
    if not base or not w:
        return {"t": t, "r": r, "status": "no_payload"}
    S_held = {i for i, x in enumerate(w) if x}
    k = len(S_held)
    # smaller totally-split primes on the same base
    try:
        primes = [q for q in gp.split_primes(base, 12, k=n_primes, hi=hi) if q < old_q]
    except Exception:
        primes = []
    if not primes:
        return {"t": t, "r": r, "status": "no_smaller_prime", "old_q": old_q}
    parts_old = block_partitions(base, old_q)
    if not parts_old:
        return {"t": t, "r": r, "status": "held_partition_failed", "old_q": old_q}
    fp_held = fingerprint(parts_old, S_held)
    # held density (once) for the group-preservation gate
    held_t, held_n = defend_harden.frob_density(held_coeffs)
    if held_n < 300:
        return {"t": t, "r": r, "status": "held_density_failed"}
    n_fp = 0
    winners = []
    for q in sorted(primes):
        parts_q = block_partitions(base, q)
        if not parts_q:
            continue
        subs = matching_subsets(parts_q, fp_held, k)
        n_fp += len(subs)
        if not subs:
            continue
        # build all fingerprint-matched subsets at this prime in ONE bnfinit (amortized)
        built = build_subsets_at(base, subs, q)
        for si, (rr, poly) in built.items():
            if rr != target_r:
                continue
            try:
                fd = gp.scoreable_disc(poly)
            except Exception:
                fd = None
            if fd is None or not str(fd).lstrip("-").isdigit():
                continue  # blank-risk model: never enqueue
            fda = abs(int(fd))
            if fda >= our_disc:
                continue
            ct, n = defend_harden.frob_density(poly)
            if n < 300:
                continue
            d = defend_harden.l1(ct, n, held_t, held_n)
            if d <= l1_max:
                winners.append({"field_disc": fda, "field_dig": len(str(fda)), "q": q,
                                "coeffs": poly, "l1": round(d, 3)})
            if len(winners) >= per_pair:
                break
        if len(winners) >= per_pair:
            break
    if not winners:
        return {"t": t, "r": r, "status": "no_group_preserved_smaller", "old_q": old_q,
                "n_fp_matched": n_fp, "our_dig": len(str(our_disc))}
    winners.sort(key=lambda wn: wn["field_disc"])
    return {"t": t, "r": r, "status": "improved", "old_q": old_q, "k": k,
            "our_dig": len(str(our_disc)), "n_fp_matched": n_fp,
            "winners": winners[:per_pair], "loss": rec.get("loss")}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--enqueue", action="store_true")
    ap.add_argument("--limit", type=int, default=15)
    ap.add_argument("--per-pair", type=int, default=2)
    ap.add_argument("--l1-max", type=float, default=0.15)
    ap.add_argument("--only", type=str, default="")
    ap.add_argument("--build-pool", action="store_true")
    args = ap.parse_args()

    if args.build_pool or not defend_harden.POOL.exists():
        print("building behind-gen12 pool ...", flush=True)
        defend_harden.build_pool()
    pool = json.load(open(defend_harden.POOL))
    pool.sort(key=lambda x: -x["loss"])
    if args.only:
        want = set(args.only.split(","))
        pool = [d for d in pool if f"{d['t']}.{d['r']}" in want]
    else:
        pool = pool[:args.limit]

    print(f"=== DEFEND-FINGERPRINT gen12: {len(pool)} behind pairs, enqueue={args.enqueue} ===",
          flush=True)
    if args.enqueue:
        store.init()
    CKPT.parent.mkdir(parents=True, exist_ok=True)
    ck = open(CKPT, "a")
    t0 = time.time()
    status_ct: dict = {}
    improved = enqueued = dig_reduced = 0
    for i, rec in enumerate(pool):
        res = harden_pair(rec, per_pair=args.per_pair, l1_max=args.l1_max)
        status_ct[res["status"]] = status_ct.get(res["status"], 0) + 1
        if res["status"] == "improved":
            improved += 1
            best = res["winners"][0]
            dig_reduced += res["our_dig"] - best["field_dig"]
            print(f"  [{i+1}/{len(pool)}] 24T{res['t']} r{res['r']} k={res['k']} "
                  f"disc {res['our_dig']}d->{best['field_dig']}d q{res['old_q']}->q{best['q']} "
                  f"L1={best['l1']} fp_matched={res['n_fp_matched']} nwin={len(res['winners'])}",
                  flush=True)
            for wn in res["winners"]:
                ck.write(json.dumps({"t": res["t"], "r": res["r"], **wn}) + "\n")
                ck.flush()
                if args.enqueue:
                    tag = f"defend:{res['t']}.{res['r']}:harden:q{wn['q']}"
                    if store.enqueue("ready", {"coeffs": wn["coeffs"]}, target=tag):
                        enqueued += 1
        else:
            extra = f" fp_matched={res.get('n_fp_matched')}" if "n_fp_matched" in res else ""
            print(f"  [{i+1}/{len(pool)}] 24T{res['t']} r{res['r']} -> {res['status']}{extra}",
                  flush=True)
    ck.close()
    if args.enqueue and enqueued:
        store.set_priority_prefix("defend:", 150.0)
    print("\n=== SUMMARY ===")
    print(f"  attempted:  {len(pool)}")
    print(f"  improved (smaller-disc, fingerprint+density group-preserved): {improved}")
    print(f"  disc digits reduced (sum best): {dig_reduced}")
    print(f"  status breakdown: {status_ct}")
    print(f"  enqueued:   {enqueued} defend:harden ready polys (priority 150)")
    print(f"  elapsed:    {time.time()-t0:.0f}s")


if __name__ == "__main__":
    main()
