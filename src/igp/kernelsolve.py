"""General F_2[H]-module kernel solver (the inverse map A -> w).

The C_2-kernel construction realizes the H-submodule ``A = <H-shifts of w>`` from a 0/1
valuation pattern ``w`` (see ``gp.cyclotomic_c2`` / ``c2_split_construct``). The *forward*
map ``w -> A`` is "the submodule generated by w". This module solves the inverse and the
bookkeeping around it for an ARBITRARY top action ``H`` (given as permutations), so the
deliberate constructor is no longer special-cased to the cyclic C_12 ideal lattice:

- ``module_basis(w, perms)``  — the submodule generated by ``w`` (forward map), as a
  canonical reduced GF(2) basis.
- ``generators(target, perms)`` — a minimal list of patterns ``w_1..w_r`` whose submodules
  sum to ``target``; the construction uses one split prime per generator. ``r = 1`` (cyclic)
  for most targets.

Vectors are Python ints used as GF(2) bitmasks (bit ``i`` = coordinate ``i``). The top acts
linearly: ``(sigma . v)`` has bit ``perm[i]`` set iff ``v`` has bit ``i`` set.
"""

from __future__ import annotations


def apply_perm(perm: list[int], v: int) -> int:
    """Act on bitmask ``v`` by ``perm`` (0-indexed image list): bit i -> bit perm[i]."""
    out = 0
    i = 0
    while v:
        if v & 1:
            out |= 1 << perm[i]
        v >>= 1
        i += 1
    return out


def rref(vectors) -> tuple[int, ...]:
    """Canonical reduced row-echelon GF(2) basis of span(vectors), as a sorted int tuple."""
    pivots: dict[int, int] = {}  # leading-bit position -> basis vector
    for v in vectors:
        cur = v
        for p in sorted(pivots, reverse=True):
            if (cur >> p) & 1:
                cur ^= pivots[p]
        if cur:
            pivots[cur.bit_length() - 1] = cur
    ps = sorted(pivots, reverse=True)
    for i, p in enumerate(ps):  # back-reduce to canonical RREF
        for q in ps[:i]:
            if (pivots[q] >> p) & 1:
                pivots[q] ^= pivots[p]
    return tuple(sorted(pivots.values()))


def orbit(w: int, perms) -> set[int]:
    """The H-orbit of ``w`` under the group generated by ``perms`` (closure)."""
    seen = {w}
    stack = [w]
    while stack:
        x = stack.pop()
        for p in perms:
            y = apply_perm(p, x)
            if y not in seen:
                seen.add(y)
                stack.append(y)
    return seen


def module_basis(w: int, perms) -> tuple[int, ...]:
    """The submodule <H-shifts of w> (forward map), as a canonical reduced basis."""
    return rref(orbit(w, perms))


def span_elements(basis) -> list[int]:
    """All 2^len(basis) F_2-combinations of ``basis`` (includes 0)."""
    els = [0]
    for b in basis:
        els += [e ^ b for e in els]
    return els


def generators(target_basis, perms) -> list[int] | None:
    """Minimal patterns whose submodules sum to span(target_basis); None if unreachable.

    Greedy: scan elements of the target (smallest popcount first — cheaper patterns,
    smaller alpha) and keep any whose orbit grows the accumulated span, until it equals
    the target. The construction realizes each returned ``w`` with its own split prime.
    """
    target = rref(target_basis)
    accum: set[int] = set()
    cur: tuple[int, ...] = ()
    chosen: list[int] = []
    for w in sorted(span_elements(target), key=lambda x: (bin(x).count("1"), x)):
        if cur == target:
            break
        if not w:
            continue
        grown = accum | orbit(w, perms)
        nb = rref(grown)
        if nb != cur:
            chosen.append(w)
            accum = grown
            cur = nb
    return chosen if cur == target else None


def cyclic_generator(target_basis, perms) -> int | None:
    """A single pattern ``w`` generating exactly span(target_basis), or None if not cyclic."""
    gens = generators(target_basis, perms)
    return gens[0] if gens and len(gens) == 1 else None
